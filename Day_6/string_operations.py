text = "python programming language"

print("Original String")
print(text)

print("Uppercase")
print(text.upper())

print("Lowercase")
print(text.lower())

print("Title Case")
print(text.title())

print("Replace word")
print(text.replace("python", "java"))

print("Split words")
print(text.split())

print("Length")
print(len(text))

print("Find position of programming")
print(text.find("programming"))

print("Check startswith")
print(text.startswith("python"))

print("Check endswith")
print(text.endswith("language"))

print("Count letter a")
print(text.count("a"))

print("Capitalized")
print(text.capitalize())